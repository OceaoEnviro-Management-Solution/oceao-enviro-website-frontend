// and those components resolve them with `Icons[name]`. `import * as Icons from 'lucide-react'`
// would put every icon in the bundle (over 1 MB), so those components import this module instead.
//
// Add an icon here when a constants file starts using a new name; an unknown name renders
// the Circle fallback.

